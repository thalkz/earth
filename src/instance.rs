use crate::scene::Transform;
use glam::{Quat, Vec3};
use wgpu::BufferAddress;

pub struct Instance {
    pub transform: Transform,
}

impl Instance {
    pub fn new(position: Vec3, rotation: Quat) -> Instance {
        Instance {
            transform: Transform::from_rotation_translation(rotation, position),
        }
    }

    #[allow(dead_code)]
    pub fn from_transform(transform: Transform) -> Instance {
        Instance { transform }
    }
}

#[repr(C)]
#[derive(Copy, Clone, bytemuck::Pod, bytemuck::Zeroable)]
pub struct InstanceRaw {
    model: [[f32; 4]; 4],
}

impl InstanceRaw {
    pub fn desc() -> wgpu::VertexBufferLayout<'static> {
        use std::mem;
        wgpu::VertexBufferLayout {
            array_stride: mem::size_of::<InstanceRaw>() as BufferAddress,
            step_mode: wgpu::VertexStepMode::Instance,
            attributes: &[
                wgpu::VertexAttribute {
                    offset: 0,
                    shader_location: 5,
                    format: wgpu::VertexFormat::Float32x4,
                },
                wgpu::VertexAttribute {
                    offset: mem::size_of::<[f32; 4]>() as wgpu::BufferAddress,
                    shader_location: 6,
                    format: wgpu::VertexFormat::Float32x4,
                },
                wgpu::VertexAttribute {
                    offset: mem::size_of::<[f32; 8]>() as wgpu::BufferAddress,
                    shader_location: 7,
                    format: wgpu::VertexFormat::Float32x4,
                },
                wgpu::VertexAttribute {
                    offset: mem::size_of::<[f32; 12]>() as wgpu::BufferAddress,
                    shader_location: 8,
                    format: wgpu::VertexFormat::Float32x4,
                },
            ],
        }
    }
}

impl From<&Instance> for InstanceRaw {
    fn from(value: &Instance) -> Self {
        InstanceRaw {
            model: value.transform.to_mat4().to_cols_array_2d(),
        }
    }
}
